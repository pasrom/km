#!/usr/bin/env bash
# Smoke test for `km doctor`: on a team brain with a local origin, every check must pass, and each
# thing that is missing (git identity, access, a newer km, a plugin, uv on the PATH) must fail with
# a fix, without hanging and in ASCII.
# Run:  bash tests/doctor_smoke.sh
set -u
source "$(dirname "$0")/lib.sh"
T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
fake_km_remote "$T/kmremote"; export KM_REPO_URL="file://$T/kmremote"
KM_REF="v$(km --version)"; KM_SHA="$(git -C "$T/kmremote" rev-parse "$KM_REF^{commit}")"
S99="$(printf '9%.0s' {1..40})"
# git and Claude Code read only what this test writes
printf '[user]\n\tname = t\n\temail = t@t\n[protocol "file"]\n\tallow = always\n' > "$T/gitconfig"
export GIT_CONFIG_GLOBAL="$T/gitconfig" GIT_CONFIG_NOSYSTEM=1 CLAUDE_CONFIG_DIR="$T/cfg"
mkdir -p "$T/home" && export HOME="$T/home"
B="$T/brain"
km init "$B" --team --name D --desc d --initials DD --folder docs=Docs >/dev/null
git -C "$B" init -q -b main && git -C "$B" add -A && git -C "$B" commit -q -m init
git init -q --bare -b main "$T/origin.git" && git -C "$B" remote add origin "$T/origin.git" && git -C "$B" push -q origin main
printf '#!/bin/sh\n# File generated by pre-commit: https://pre-commit.com\n' > "$B/.git/hooks/pre-commit"   # as `pre-commit install` leaves it
cp "$B/.git/hooks/pre-commit" "$B/.git/hooks/pre-push"; chmod +x "$B/.git/hooks/pre-commit" "$B/.git/hooks/pre-push"   # a team brain's config names both
doctor(){ out="$(cd "$B" && km doctor "$@" 2>&1)"; rc=$?; }

doctor
{ [ "$rc" = 0 ] && out_has "Everything needed is set up" && out_has "ok    origin" && out_has "has everything origin has" \
  && out_has "ok    km $KM_REF is the version the brain pins"; } && ok "a set-up brain passes" || no "a set-up brain passes ($out)"
LC_ALL=C grep -q '[^ -~]' <<< "$out" && no "the output is ASCII" || ok "the output is ASCII"
out="$(cd "$B" && PYTHONPATH="$REPO/src" "$PY" -c 'import sys, runpy
sys.modules["yaml"] = None                      # PyYAML missing
sys.argv = ["km", "doctor", "--offline"]; runpy.run_module("km", run_name="__main__")' 2>&1)"
out_has "km doctor:" && ! out_has "Traceback" && ok "runs without PyYAML" || no "runs without PyYAML ($out)"

printf '[user]\n\tname = t\n' > "$T/noemail"
out="$(cd "$B" && GIT_CONFIG_GLOBAL="$T/noemail" km doctor 2>&1)"; rc=$?
{ [ "$rc" = 1 ] && out_has "FAIL  git does not know your email" && out_has 'git config --global user.email'; } \
  && ok "a missing git email fails with the command that sets it" || no "missing git email ($out)"

echo x > "$B/scratch.md"; doctor
{ [ "$rc" = 0 ] && out_has "note  1 changed or new file"; } && ok "uncommitted changes are a note, not a failure" || no "uncommitted changes ($out)"
rm "$B/scratch.md"

git clone -q "$T/origin.git" "$T/other" && git -C "$T/other" commit -q --allow-empty -m newer && git -C "$T/other" push -q origin main
doctor
{ [ "$rc" = 1 ] && out_has "FAIL  branch main lacks changes that are on origin"; } && ok "a brain behind origin fails" || no "behind origin ($out)"
git -C "$B" commit -q --allow-empty -m local; doctor
fix="$(sed -n 's/.*`\(git pull --rebase origin main\)`.*/\1/p' <<< "$out")"
{ [ "$rc" = 1 ] && [ -n "$fix" ] && ( cd "$B" && $fix -q ) && doctor && [ "$rc" = 0 ]; } \
  && ok "a diverged brain fails with a pull that works" || no "diverged brain ($out)"
doctor --offline
{ [ "$rc" = 0 ] && out_has "skip  origin .* (offline)"; } && ok "--offline skips the origin" || no "--offline ($out)"

# origin is a fork: the upstream brain (remote `upstream`) is what the branch and the fork must have
git -C "$B" push -q origin main && git init -q --bare -b main "$T/up.git" && git -C "$B" push -q "$T/up.git" main && git -C "$B" remote add upstream "$T/up.git"
doctor
{ [ "$rc" = 0 ] && out_has "ok    upstream .*up.git answers" && out_has "ok    your fork's main has everything upstream has" \
  && out_has "ok    branch main has everything upstream has"; } && ok "a fork at upstream passes" || no "fork at upstream ($out)"
git clone -q "$T/up.git" "$T/upw" && git -C "$T/upw" commit -q --allow-empty -m newer && git -C "$T/upw" push -q origin main
doctor
{ [ "$rc" = 1 ] && out_has "FAIL  your fork's main lacks changes that are on the upstream brain" \
  && out_has "FAIL  branch main lacks changes that are on the upstream brain" && out_has "fix: run .km sync."; } \
  && ok "a fork behind the upstream brain fails, with km sync as the fix" || no "fork behind upstream ($out)"
git -C "$B" checkout -q -b topic; doctor
{ [ "$rc" = 1 ] && out_has "note  branch topic lacks changes that are on the upstream brain" && out_has "then rebase topic onto upstream's main" \
  && ! out_has "FAIL  branch topic"; } && ok "a work branch behind upstream is a note that names the rebase" || no "work branch behind upstream ($out)"
git -C "$B" checkout -q main
{ ( cd "$B" && km sync >/dev/null 2>&1 ) && doctor && [ "$rc" = 0 ] && out_has "ok    your fork's main has everything upstream has"; } \
  && ok "km sync brings the branch and the fork up to upstream, and doctor passes" || no "km sync fixes it ($out)"
git -C "$B" branch -q -D topic; git -C "$B" remote remove upstream

git -C "$B" remote set-url origin "file://$T/nope.git"
start=$SECONDS; doctor
{ [ "$rc" = 1 ] && out_has "FAIL  origin: no access to" && out_has "fix: sign in" && [ $((SECONDS-start)) -lt 20 ]; } \
  && ok "an origin that cannot be read fails at once, with a fix" || no "unreadable origin ($out)"
git -C "$B" remote set-url origin "$T/origin.git"
git -C "$B" remote set-url origin "https://someone:s3cret@127.0.0.1:9/brain.git"; doctor
{ [ "$rc" = 1 ] && out_has "FAIL  origin: https://127.0.0.1:9/brain.git cannot be reached" && ! out_has "s3cret"; } \
  && ok "an origin that does not answer is a network problem, its token not shown" || no "token in URL ($out)"
git -C "$B" remote set-url origin "$T/origin.git"

git init -q "$T/peer" && git -C "$T/peer" commit -q --allow-empty -m peer
git -C "$B" submodule add -q "$T/peer" brains/peer >/dev/null 2>&1 && git -C "$B" commit -q -m mount && git -C "$B" push -q origin main
doctor; out_has "ok    mounted brains/peer answers" && ok "a mounted brain that answers passes" || no "mounted brain ($out)"
git -C "$B" submodule deinit -q -f brains/peer; doctor
{ [ "$rc" = 0 ] && out_has "note  mounted brains/peer is not checked out" && out_has "submodule update --init \"brains/peer\""; } \
  && ok "a mounted brain not checked out is a note with the command" || no "mounted brain not checked out ($out)"
git -C "$B" config -f .gitmodules submodule.brains/peer.url "file://$T/gone"; doctor
{ [ "$rc" = 0 ] && out_has "note  mounted brains/peer is not initialised here and file://.*/gone does not answer" \
  && out_has 'fix: sign in to the host once if you have not .*ask the brain.s owner for read access; if not, leave it out here, so km sync does not try to check it out: .git config "submodule.brains/peer.update" none.$'; } \
  && ok "a mount never initialised that cannot be read is a note naming the login, read access and the skip" || no "unreadable uninitialised mount ($out)"
# no login or an unknown host key is this computer's to set up: a failure, initialised or not
printf '#!/bin/sh\necho "$FAKE_SSH" >&2; exit 255\n' > "$T/fakessh"; chmod +x "$T/fakessh"
git -C "$B" config -f .gitmodules submodule.brains/peer.url "ssh://git@host.invalid/peer.git"
out="$(cd "$B" && GIT_SSH_COMMAND="$T/fakessh" FAKE_SSH="Host key verification failed." km doctor 2>&1)"; rc=$?
{ [ "$rc" = 1 ] && out_has "FAIL  mounted brains/peer: this computer does not know the host key"; } \
  && ok "an unknown host key of a mount never initialised fails with the host-key fix" || no "uninitialised mount host key ($out)"
out="$(cd "$B" && GIT_SSH_COMMAND="$T/fakessh" FAKE_SSH="git@host.invalid: Permission denied (publickey)." km doctor 2>&1)"; rc=$?
{ [ "$rc" = 1 ] && out_has "FAIL  mounted brains/peer: no access to ssh://host.invalid/peer.git" && out_has "fix: sign in to the host once"; } \
  && ok "no login for a mount never initialised fails with the sign-in fix" || no "uninitialised mount no login ($out)"
git -C "$B" config -f .gitmodules submodule.brains/peer.url "https://127.0.0.1:9/peer.git"; doctor
{ [ "$rc" = 1 ] && out_has "FAIL  mounted brains/peer: https://127.0.0.1:9/peer.git cannot be reached" && ! out_has "skipped here (not initialised)"; } \
  && ok "a mount never initialised behind a dead network is a network failure, not a question of access" || no "uninitialised mount offline ($out)"
git -C "$B" checkout -q .gitmodules
# a mount some readers of the brain may not read: a failure until this computer leaves it out
git -C "$B" submodule update -q --init brains/peer && git -C "$B" config submodule.brains/peer.url "file://$T/gone"; doctor
{ [ "$rc" = 1 ] && out_has "FAIL  mounted brains/peer: no access to file://.*/gone" && out_has "ask the owner for read access" \
  && out_has 'leave it out on this computer: .git config "submodule.brains/peer.update" none. (.git submodule update --init. and km sync then skip it)'; } \
  && ok "a mounted brain that cannot be read fails, naming read access and the skip" || no "unreadable mounted brain ($out)"
git -C "$B" config submodule.brains/peer.update none; doctor
{ [ "$rc" = 0 ] && out_has "note  mounted brains/peer is skipped here (update = none)$" && ! out_has "FAIL  mounted"; } \
  && ok "an unreadable mount this computer skips (update = none) is a note" || no "skipped mount ($out)"
git -C "$B" config --unset submodule.brains/peer.update; git -C "$B" config submodule.brains/peer.active false; doctor
{ [ "$rc" = 0 ] && out_has "note  mounted brains/peer is skipped here (inactive)"; } && ok "an unreadable inactive mount is a note" || no "inactive mount ($out)"
git -C "$B" config --unset submodule.brains/peer.active; git -C "$B" config submodule.brains/peer.url "$T/peer"
git -C "$B" submodule deinit -q -f brains/peer && git -C "$B" config submodule.brains/peer.update none; doctor
{ [ "$rc" = 0 ] && out_has "note  mounted brains/peer is skipped here (update = none)$" && ! out_has "is not checked out"; } \
  && ok "a readable mount left out on purpose is named as skipped, not as one to check out" || no "skipped readable mount ($out)"
git -C "$B" config --unset submodule.brains/peer.update
git init -q "$T/my peer" && git -C "$T/my peer" commit -q --allow-empty -m peer
git -C "$B" submodule add -q "$T/my peer" "brains/my peer" >/dev/null 2>&1 && git -C "$B" commit -q -m spaces; doctor
{ out_has "ok    mounted brains/my peer answers" && ! out_has "FAIL  mounted"; } && ok "a mounted brain with a space in its path" || no "space in path ($out)"
git -C "$B" submodule deinit -q -f "brains/my peer"; git -C "$B" config -f .gitmodules "submodule.brains/my peer.url" ../gone.git; doctor
{ [ "$rc" = 0 ] && out_has "note  mounted brains/my peer is not initialised here and .*/gone.git does not answer" \
  && out_has '"submodule.brains/my peer.update" none'; } \
  && ok "a relative URL is resolved against origin and checked" || no "relative submodule URL ($out)"
git -C "$B" checkout -q .gitmodules
# .gitmodules is whoever edits the brain's: no fix line may carry a name or path a shell would act on
git -C "$B" config -f .gitmodules 'submodule.x$(touch pwned).path' brains/x
git -C "$B" config -f .gitmodules 'submodule.x$(touch pwned).url' "file://$T/gone"
git -C "$B" config -f .gitmodules 'submodule.y.path' 'brains/`touch y`'
git -C "$B" config -f .gitmodules 'submodule.y.url' "$T/peer"; doctor
git -C "$B" config -f .gitmodules 'submodule.z.path' "$(printf 'brains/z\n  ok    all fine')"
git -C "$B" config -f .gitmodules 'submodule.z.url' "file://$T/gone"; doctor
{ out_has "note  mounted brains/x is not initialised here" && ! out_has 'pwned' && out_has "set its .update. to none in the brain's git config" \
  && out_has 'fix: check it out with .git submodule update --init.$' && ! out_has 'init "brains/`' \
  && out_has "note  mounted brains/?touch y? is not checked out" && ! out_has '`touch y`' \
  && out_has "mounted brains/z?  ok    all fine is not initialised here" && ! out_has "^  ok    all fine"; } \
  && ok "a mount name or path with shell syntax or a newline gets no command, and cannot fake a line" || no "hostile mount name ($out)"
git -C "$B" checkout -q .gitmodules

repin "$KM_SHA" "$KM_REF" "$S99" v99.0.0 "$B"/.github/workflows/*.yml "$B/.pre-commit-config.yaml"; doctor
{ [ "$rc" = 1 ] && out_has "FAIL  km $KM_REF is older than the brain's v99.0.0" && out_has "ask the brain.s maintainer"; } \
  && ok "a km older than the brain's pin fails" || no "older km ($out)"
repin "$S99" v99.0.0 "$(git -C "$T/kmremote" rev-parse v0.9.0)" v0.9.0 "$B"/.github/workflows/*.yml "$B/.pre-commit-config.yaml"; doctor
{ [ "$rc" = 0 ] && out_has "note  km $KM_REF; the brain pins v0.9.0"; } && ok "a km newer than the pin is a note" || no "newer km ($out)"
git -C "$B" checkout -q .

mkdir -p "$B/.claude" "$T/cfg/plugins"
cat > "$B/.claude/settings.json" <<'JSON'
{"extraKnownMarketplaces": {"team": {"source": {"source": "github", "repo": "owner/team-plugins"}}},
 "enabledPlugins": {"km@team": true, "docs@team": true, "off@team": false}}
JSON
cat > "$T/cfg/plugins/installed_plugins.json" <<JSON
{"version": 2, "plugins": {
  "km@team": [{"scope": "user", "installPath": "/x"}],
  "docs@team": [{"scope": "project", "projectPath": "$T/elsewhere", "installPath": "/x"}]}}
JSON
printf '{"other": {}}' > "$T/cfg/plugins/known_marketplaces.json"; doctor
{ [ "$rc" = 1 ] && out_has "FAIL  plugin km@team is installed, but its marketplace team is not registered" \
  && out_has "fix: in Claude Code: ./plugin marketplace add owner/team-plugins.$" && out_has "FAIL  plugin docs@team is not installed" \
  && out_has "/plugin marketplace add owner/team-plugins., then ./plugin install docs@team" && ! out_has "off@team"; } \
  && ok "a plugin nobody installed, or whose marketplace is gone, fails with the marketplace to add" || no "plugins ($out)"
printf '{"team": {}}' > "$T/cfg/plugins/known_marketplaces.json"; doctor
{ out_has "fix: in Claude Code: ./plugin install docs@team" && out_has "ok    plugin km@team is installed"; } && ok "a known marketplace is not added again" || no "known marketplace ($out)"
rm "$T/cfg/plugins/known_marketplaces.json"; doctor
out_has "ok    plugin km@team is installed" && ok "no marketplace list on this computer is no reason to fail an installed plugin" || no "no known_marketplaces.json ($out)"
printf '{"enabledPlugins": ["x@team"], "extraKnownMarketplaces": "team"}' > "$B/.claude/settings.json"
printf '{"plugins": ["x"]}' > "$T/cfg/plugins/installed_plugins.json"; doctor
! out_has "Traceback" && ok "odd values in the JSON files are no crash" || no "odd JSON values ($out)"
printf '{"enabledPlugins": {"docs@team": true}, "extraKnownMarketplaces": {"team": {"source": "github"}}}' > "$B/.claude/settings.json"
printf '{"plugins": {"docs@team": [{"scope": "project", "projectPath": "%s"}]}}' "$(cd "$B" && { pwd -W 2>/dev/null || pwd; })" > "$T/cfg/plugins/installed_plugins.json"; doctor
{ ! out_has "Traceback" && out_has "ok    plugin docs@team is installed"; } && ok "a project install in the brain counts" || no "project install ($out)"
printf '{}' > "$T/cfg/plugins/installed_plugins.json"
mkdir -p "$T/cfg/plugins/synced/bucket/docs~g2"; doctor
{ [ "$rc" = 0 ] && out_has "ok    plugin docs@team is installed"; } && ok "a plugin synced by the organization counts" || no "synced plugin ($out)"

if [ "$SEP" = ":" ]; then   # PATH games need a POSIX layout
  mkdir -p "$T/bin" "$T/home/.local/bin" && : > "$T/home/.local/bin/uv"
  ln -s "$(command -v git)" "$T/bin/git" && ln -s "$(command -v "$PY")" "$T/bin/py"
  out="$(cd "$B" && HOME="$T/home" PATH="$T/bin" PYTHONPATH="$REPO/src" "$T/bin/py" -m km doctor --offline 2>&1)"
  out_has "FAIL  uv is installed in .* but that folder is not on the PATH" && ok "uv installed but not on the PATH fails" || no "uv off the PATH ($out)"
  rm "$T/home/.local/bin/uv"
  repin "$KM_SHA" "$KM_REF" "$(git -C "$T/kmremote" rev-parse v0.9.0)" v0.9.0 "$B"/.github/workflows/*.yml "$B/.pre-commit-config.yaml"
  out="$(cd "$B" && PATH="$T/bin" PYTHONPATH="$REPO/src" "$T/bin/py" -m km doctor --offline 2>&1)"
  out_has "the brain pins v0.9.0, which km cannot run without uv" && ok "without uv a differing pin says km cannot run it" || no "pin without uv ($out)"
  git -C "$B" checkout -q .
  out="$(cd "$B" && PATH="$T/bin" PYTHONPATH="$REPO/src" "$T/bin/py" -c 'import sys, runpy
sys.modules["yaml"] = None
sys.argv = ["km", "doctor", "--offline"]; runpy.run_module("km", run_name="__main__")' 2>&1)"
  out_has "FAIL  uv is not installed, and this Python has no PyYAML" && ok "no uv and no PyYAML fails: km cannot run" || no "no uv, no PyYAML ($out)"
  # the launcher: nothing to run km with, then uv only where its installer put it
  mkdir -p "$T/bare" && ln -s "$(command -v dirname)" "$T/bare/dirname"
  out="$(cd "$B" && PATH="$T/bare" "$BASH" "$REPO/skills/km/bin/km" doctor 2>&1)"; rc=$?
  { [ "$rc" = 1 ] && out_has "km cannot start on this computer" && out_has "install.ps1" && out_has "git is missing as well"; } \
    && ok "the launcher says what to install when nothing can run km" || no "launcher without uv or Python ($out)"
  printf '#!/bin/sh\necho "fake uv $*"\n' > "$T/home/.local/bin/uv" && chmod +x "$T/home/.local/bin/uv"
  out="$(cd "$B" && PATH="$T/bare" "$BASH" "$REPO/skills/km/bin/km" doctor 2>&1)"
  out_has "fake uv run .* -m km doctor" && ok "the launcher finds uv off the PATH, before a restart" || no "launcher uv off PATH ($out)"
  rm "$T/home/.local/bin/uv"
  rm "$T/bin/git"
  out="$(cd "$B" && PATH="$T/bin" PYTHONPATH="$REPO/src" "$T/bin/py" -m km doctor 2>&1)"; rc=$?
  { [ "$rc" = 1 ] && out_has "FAIL  git is not installed" && ! out_has "Traceback"; } && ok "without git it says so" || no "no git ($out)"
fi

# --- the pre-commit hook, line endings, and GitHub access ---
mv "$B/.git/hooks/pre-commit" "$T/hook.bak"; doctor
{ [ "$rc" = 1 ] && out_has "FAIL  the pre-commit hook is not installed" && out_has "pre-commit install. in the brain"; } \
  && ok "a missing pre-commit hook fails with the command that installs it" || no "missing hook ($out)"
mv "$T/hook.bak" "$B/.git/hooks/pre-commit"
mv "$B/.git/hooks/pre-push" "$T/push.bak"; doctor
{ [ "$rc" = 1 ] && out_has "FAIL  the pre-push hook is not installed" && out_has "pre-commit install. in the brain"; } \
  && ok "a team brain's config names a pre-push hook, so git needs that hook too" || no "missing pre-push hook ($out)"
cp "$B/.pre-commit-config.yaml" "$T/config.bak"; grep -v "^default_install_hook_types" "$T/config.bak" > "$B/.pre-commit-config.yaml"; doctor
! out_has "pre-push" && ok "a config that names no install hook types is asked for the pre-commit hook only" || no "pre-push asked without install types ($out)"
{ printf "default_install_hook_types:\n  - 'pre-commit'\n  - pre-push\n"; grep -v "^default_install_hook_types" "$T/config.bak"; } > "$B/.pre-commit-config.yaml"; doctor
out_has "FAIL  the pre-push hook is not installed" && ok "a block-style, quoted install types list is read too" || no "block-style types ($out)"
printf '#!/bin/sh\necho husky\n' > "$B/.git/hooks/pre-push"; chmod +x "$B/.git/hooks/pre-push"; doctor
{ out_has "FAIL  the pre-push hook is not installed" && ! out_has "not executable"; } && ok "an executable hook another tool wrote is not taken for a non-executable one of pre-commit's" || no "foreign hook ($out)"
rm "$B/.git/hooks/pre-push"
mv "$T/config.bak" "$B/.pre-commit-config.yaml"; mv "$T/push.bak" "$B/.git/hooks/pre-push"; doctor
out_has "ok    the pre-push hook is installed" && ok "the installed pre-push hook passes" || no "pre-push hook ($out)"
if [ "$SEP" = ":" ]; then
  chmod -x "$B/.git/hooks/pre-commit"; doctor
  out_has "FAIL  the pre-commit hook is there but not executable" && ok "a hook git cannot execute fails" || no "non-executable hook ($out)"
  chmod +x "$B/.git/hooks/pre-commit"
fi
printf 'a\r\nb\r\n' > "$B/docs/crlf.md"; git -C "$B" add docs/crlf.md 2>/dev/null && git -C "$B" commit -q -m crlf; doctor
out_has "note  1 file(s) have CRLF line endings here, e.g. docs/crlf.md" && ok "CRLF files in the working tree are a note" || no "CRLF note ($out)"
git -C "$B" rm -q docs/crlf.md && git -C "$B" commit -q -m rm
printf '*.bat text eol=crlf\n*.bin -text\n' >> "$B/.gitattributes"; printf 'a\r\n' > "$B/run.bat"; printf 'a\r\n' > "$B/raw.bin"
git -C "$B" add .gitattributes run.bat raw.bin 2>/dev/null && git -C "$B" commit -q -m keep; doctor
out_has "ok    text files have LF line endings" && ok "files kept in CRLF on purpose do not count" || no "eol=crlf and -text ($out)"
git -C "$B" rm -q run.bat raw.bin && git -C "$B" checkout -q HEAD~1 -- .gitattributes && git -C "$B" commit -q -m unkeep
mv "$B/.gitattributes" "$T/ga.bak"; git -C "$B" rm -q --cached .gitattributes   # git also reads it from the index
out="$(cd "$B" && GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=core.autocrlf GIT_CONFIG_VALUE_0=true km doctor --offline 2>&1)"
out_has "FAIL  the brain sets no line ending" && ok "autocrlf without the brain's .gitattributes fails" || no "autocrlf without attributes ($out)"
mv "$T/ga.bak" "$B/.gitattributes"; git -C "$B" add .gitattributes
if [ "$SEP" = ":" ]; then   # a stand-in gh on the PATH
  G="$T/ghstub"; mkdir -p "$G"
  cat > "$G/gh" <<'SH'
#!/bin/sh
[ "$GH_SLOW" = all ] && exec sleep 30                 # a network that does not answer
case "$*" in
  *deployment-branch-policies*) [ "$GH_SLOW" = some ] || [ "$GH_SLOW" = policies ] && exec sleep 30 ;;
  *graphql*|*mounted-pins*) [ "$GH_SLOW" = some ] && exec sleep 30 ;;
esac
case "$*" in
  "api --hostname github.com user --jq .login") [ -n "$GH_LOGIN" ] && echo "$GH_LOGIN" || exit 1 ;;
  "auth status --hostname github.com") [ -n "$GH_AUTH" ] ;;
  "api --hostname github.com repos/o/r --jq [.permissions.push, .full_name] | @tsv") printf '%s\tO/R\n' "$GH_PUSH" ;;
  "api --hostname github.com graphql -f query="*) [ "$GH_FORK" = me ] && echo me/r-1 ;;
  "api --hostname github.com repos/O/R/environments/mounted-pins --jq .deployment_branch_policy"*) [ -n "$GH_ENV" ] && echo "$GH_ENV" || exit 1 ;;
  "api --hostname github.com repos/O/R/environments/mounted-pins/deployment-branch-policies --jq"*) echo "$GH_BRANCHES" ;;
  *) exit 2 ;;
esac
SH
  chmod +x "$G/gh"
  ghcheck(){ out="$(PATH="$G:$PATH" kmpy -c 'import km.doctor as d
d.check_github("https://github.com/o/r.git", False)
for s, w, f in d.results: print(s, w, "|", f)' 2>&1)"; }
  GH_LOGIN= ghcheck; out_has "FAIL gh is not signed in" && ok "gh without a login fails with gh auth login" || no "gh login ($out)"
  GH_LOGIN= GH_AUTH=1 ghcheck; out_has "FAIL gh is signed in but github.com did not answer" && ok "a network error is not taken for a missing login" || no "gh network ($out)"
  GH_LOGIN=me GH_PUSH=true ghcheck; out_has "ok you can push branches to O/R" && ok "push access is ok" || no "push access ($out)"
  out="$(GH_LOGIN=me GH_PUSH=false PATH="$G:$PATH" kmpy -c 'import km.doctor as d; print(d.check_github("https://github.com/o/r.git", False))' 2>&1)"
  [ "$out" = O/R ] && ok "the GitHub check names the repository for the checks that follow, also without push access" || no "check_github returns the repo ($out)"
  GH_LOGIN=me GH_PUSH=false GH_FORK=me ghcheck; out_has "ok you contribute through your fork me/r-1" && ok "a fork is found, also under another name" || no "fork found ($out)"
  GH_LOGIN=me GH_PUSH=false GH_FORK=other ghcheck; out_has "note you can read O/R but not push to it" && ok "no fork yet is a note" || no "no fork ($out)"
  E="$T/envbrain"; mkdir -p "$E/.github/workflows" && touch "$E/.gitmodules" "$E/.github/workflows/bump-mounted-pins.yml"
  # gh with a time limit of 1 s, against a gh that does not answer for 30 s: GH_SLOW=all waits out two
  # time limits (the login, the environment), about 2 s; a call km did not cut off would take 30 s
  slow(){ out="$(PATH="$G:$PATH" kmpy -c 'import sys, pathlib, km.remotes, km.doctor as d
km.remotes.TIMEOUT = 1
d.check_github("https://github.com/o/r.git", False); d.check_mounted_pins(pathlib.Path(sys.argv[1]), "O/R")
for s, w, f in d.results: print(s, w, "|", f)' "$E" 2>&1)"; }
  start=$SECONDS; GH_SLOW=all slow
  { out_has "FAIL gh gave no answer within 1 s for the login | check the network" && ! out_has "not signed in" && [ $((SECONDS-start)) -lt 10 ]; } \
    && ok "gh that does not answer is cut off and reported as the network, not as a missing login" || no "gh timeout ($out)"
  GH_SLOW=some GH_LOGIN=me GH_PUSH=false slow
  { out_has "note gh gave no answer within 1 s for your forks of O/R" && ! out_has "no fork of it yet" \
    && out_has "note gh gave no answer within 1 s for the environment mounted-pins of O/R" && ! out_has "has no environment"; } \
    && ok "a gh call that times out later is a skip of that check, not a wrong answer" || no "gh later timeout ($out)"
  GH_SLOW=policies GH_ENV=custom GH_LOGIN=me GH_PUSH=true slow
  { out_has "note gh gave no answer within 1 s for the environment mounted-pins of O/R" && ! out_has "open to no branch"; } \
    && ok "a timeout on the environment's branch list is no answer, not an environment open to no branch" || no "branch policies timeout ($out)"
  envcheck(){ out="$(PATH="$G:$PATH" kmpy -c 'import sys, pathlib, km.doctor as d
d.check_mounted_pins(pathlib.Path(sys.argv[1]), "O/R")
for s, w, f in d.results: print(s, w, "|", f)' "$1" 2>&1)"; }
  GH_ENV= envcheck "$E"; out_has "note O/R has no environment mounted-pins" && ok "a brain with mounts and the pins workflow but no environment gets a note" || no "missing environment ($out)"
  GH_ENV=open envcheck "$E"; out_has "note the environment mounted-pins of O/R is open to every branch" && ok "an environment open to every branch gets a note" || no "open environment ($out)"
  GH_ENV=protected envcheck "$E"; out_has "open to every protected branch, not to main alone" && ok "an environment open to protected branches gets a note" || no "protected environment ($out)"
  GH_ENV=custom GH_BRANCHES="main release" envcheck "$E"; out_has "open to main release, not to main alone" && ok "an environment open to main and another branch gets a note" || no "custom environment ($out)"
  GH_ENV=custom GH_BRANCHES=main envcheck "$E"; out_has "ok O/R has the environment mounted-pins, restricted to main" && ok "an environment restricted to main is ok" || no "restricted environment ($out)"
  rm "$E/.gitmodules"; GH_ENV= envcheck "$E"; ! out_has "mounted-pins" && ok "without mounts the environment is not asked for" || no "no mounts, no check ($out)"
  C="$T/cred"; git init -q "$C"
  login(){ out="$(PATH="$G:$PATH" kmpy -c 'import sys, pathlib, km.doctor as d
d.check_git_login(pathlib.Path(sys.argv[1]), sys.argv[2])
for s, w, f in d.results: print(s, w, "|", f)' "$C" "${1:-https://github.com/o/r.git}" 2>&1)"; }
  login; { out_has "FAIL git has no login for github.com" && out_has "gh auth setup-git"; } \
    && ok "an https GitHub origin without a credential helper fails with gh auth setup-git" || no "no credential helper ($out)"
  git -C "$C" config credential.helper store; login
  { out_has "note git pushes to github.com with its own login helper (store)" && out_has "gh auth setup-git"; } \
    && ok "another credential helper is a note" || no "other credential helper ($out)"
  git -C "$C" config credential.https://github.com.helper '' && git -C "$C" config --add credential.https://github.com.helper '!/usr/bin/gh auth git-credential'; login
  out_has "ok git pushes to github.com with gh's login" && ok "the helper gh auth setup-git writes is ok" || no "gh credential helper ($out)"
  git -C "$C" config --unset-all credential.https://github.com.helper; login git@github.com:o/r.git
  [ -z "$out" ] && ok "an ssh GitHub origin needs no credential helper" || no "ssh origin and credential helper ($out)"
  git -C "$C" remote add origin https://github.com/o/r.git && git -C "$C" config url.git@github.com:.pushInsteadOf https://github.com/; login
  [ -z "$out" ] && ok "an https origin that pushes over ssh (pushInsteadOf) needs no credential helper" || no "pushInsteadOf ($out)"
  git -C "$C" config --unset url.git@github.com:.pushInsteadOf; git -C "$C" config credential.https://github.com/o.helper '!gh auth git-credential'; login
  out_has "ok git pushes to github.com with gh's login" && ok "a helper scoped to the owner's path counts" || no "path-scoped helper ($out)"
  git -C "$C" config --unset-all credential.https://github.com/o.helper; git -C "$C" config --unset credential.helper
  printf '[credential "https://github.com"]\n\thelper =\n' >> "$GIT_CONFIG_GLOBAL"; git -C "$C" config credential.helper '!'; login
  { out_has "note git pushes to github.com with its own login helper (a command)" && ! out_has Traceback; } \
    && ok "a reset for github.com followed by a later helper counts, as git calls it; a bare ! is no crash" || no "helper list ($out)"
  git -C "$C" config --unset credential.helper; git -C "$C" config credential.https://github.com/other.helper store; login
  out_has "FAIL git has no login" && ok "a helper for another path on the host does not count" || no "other path helper ($out)"
  git -C "$C" config --unset credential.https://github.com/other.helper
  git -C "$C" remote set-url origin https://me:t0ken@github.com/o/r.git; login
  { out_has "note git pushes to github.com with a login written into origin's URL" && ! out_has t0ken; } \
    && ok "a login in origin's URL is a note, its token not shown" || no "token in push URL ($out)"
  git -C "$C" remote set-url origin https://github.com/o/r.git
  out="$(PATH="$G:$PATH" kmpy -c 'import km.doctor as d
d.check_github("git@github.com:o/r.git", True); d.check_github("https://gitlab.com/o/r.git", False)
print(d.results)' 2>&1)"
  { out_has "gh login and access (offline)" && ! out_has "gitlab"; } && ok "an ssh GitHub origin is recognised, another host is skipped" || no "github url forms ($out)"
fi

