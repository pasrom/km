"""The ownership table in a brain's CONVENTIONS.md: where each kind of fact lives.

The `## Ownership` section holds two tables. The first is written by hand (Topic | Home | Notes): the
doc, folder, mount or URL that is the home of a kind of fact. The second, under `### Mounted
repositories` between the lines BEGIN and END, is generated by `km gen-index` from .gitmodules alone
(Mount | Repository | Branch | Holds): one row per submodule whose path the git index holds as a
gitlink, sorted by path. Nothing is read from inside a mount and no pin is listed, so moving a pin
leaves the table as it is. Holds is `submodule.<name>.km-owns`, a key of km's that git ignores.
Without the markers the file is left alone; with broken ones `km gen-index` writes nothing. Marker lines
inside fenced code are examples, not markers, and each marker line closes its comment on that line.
The file is read with LF and written back with the line ending it has (CRLF where it has any); a
CONVENTIONS.md or .gitmodules that is a symbolic link is neither read nor written through.

Every value from .gitmodules is made safe for one table cell: bytes that do not decode become U+FFFD,
format characters (zero-width, bidi) are dropped, whitespace (a newline too) collapses, control
characters and backticks become `?` (km.paths.printable), `|` is escaped, a cell holds at most
CELL_MAX characters. Mount, Repository and Branch are code spans; in Holds, plain text, `[` and `]`
become spaces and `<` is written `&lt;`. A url loses its user info (a token), query, fragment and
trailing `.git`. Two submodule names for one path give one row.
"""
from __future__ import annotations

import re
import unicodedata
from pathlib import Path

from km.paths import command, git, printable, submodule_config, write_text

FILE = "CONVENTIONS.md"
BEGIN = "<!-- km:ownership:begin"
END = "<!-- km:ownership:end -->"
# Matched as whole lines only: a value from .gitmodules never starts a line of the table.
_BEGIN = re.compile(r"(?m)^<!-- km:ownership:begin\b[^\n]*")
_END = re.compile(r"(?m)^<!-- km:ownership:end\b[^\n]*")
_SECTION = re.compile(r"(?m)^## Ownership[ \t]*$")
MOUNTS_HEADING = re.compile(r"(?mi)^#{1,6}[ \t]+Mounted repositories[ \t]*#*[ \t]*$")
_H2 = re.compile(r"(?m)^## ")
NONE = "_None mounted._"
HEADER = "| Mount | Repository | Branch | Holds |\n|---|---|---|---|"
# The section `km init` writes and `km upgrade` appends, its generated block empty (as render() leaves
# it with no mount). Both CONVENTIONS templates carry this text verbatim (a test checks it).
SECTION = f"""## Ownership

Where each kind of fact lives: a doc that states such a fact links its home instead of restating it, and `/km review` looks the home up here first. One row per topic; the home is a link to the doc, folder or mounted repository that holds it, or the URL of the source outside the brain.

| Topic | Home | Notes |
|-------|------|-------|

### Mounted repositories

What each mounted brain or shared resource holds. `km gen-index` writes this table from `.gitmodules` and `km validate` reports it when stale: do not edit it here. To say what a mount holds, run `git config -f .gitmodules submodule.<name>.km-owns "<topics>"`, then `km gen-index`, and commit `.gitmodules` with `CONVENTIONS.md`.

{BEGIN}: generated by km gen-index from .gitmodules -->

{NONE}

{END}
"""


def linked(root: Path) -> list[str]:
    """CONVENTIONS.md and .gitmodules where either is a symbolic link, which km neither reads nor writes
    through: it may point anywhere, outside the brain too."""
    return [n for n in (FILE, ".gitmodules") if (root / n).is_symlink()]


def read(root: Path) -> str | None:
    """CONVENTIONS.md with its line endings as LF (as km reads every Markdown file), or None when there is
    none, it is a symbolic link or no regular file, or it is not UTF-8."""
    path = root / FILE
    if path.is_symlink() or not path.is_file():
        return None
    try:
        return path.read_bytes().decode("utf-8").replace("\r\n", "\n")
    except (OSError, UnicodeDecodeError):
        return None


def write(root: Path, text: str) -> None:
    """Write CONVENTIONS.md (LF in `text`) with the line ending the file has: CRLF where it has any."""
    path = root / FILE
    crlf = path.is_file() and b"\r\n" in path.read_bytes()
    write_text(path, text.replace("\n", "\r\n") if crlf else text)


_FENCE = re.compile(r"(?m)^ {0,3}(`{3,}|~{3,})[^\n]*$")


def _fenced(text: str) -> list[tuple[int, int]]:
    """The (start, end) offsets of each fenced code block; an unclosed fence runs to the end."""
    spans, pos = [], 0
    while mo := _FENCE.search(text, pos):
        mark = mo.group(1)
        if mark[0] == "`" and "`" in mo.group(0)[mo.end(1) - mo.start():]:
            pos = mo.end()                      # a backtick in the info string: no fence
            continue
        close = re.compile(rf"(?m)^ {{0,3}}{re.escape(mark[0])}{{{len(mark)},}}[ \t]*$")
        cm = close.search(text, mo.end())
        spans.append((mo.start(), cm.end() if cm else len(text)))
        pos = cm.end() if cm else len(text)
    return spans


def _unfenced(rx: re.Pattern, text: str) -> list[re.Match]:
    """The matches of `rx` that start outside every fenced code block."""
    spans = _fenced(text)
    return [m for m in rx.finditer(text) if not any(a <= m.start() < b for a, b in spans)]


def _markers(text: str) -> tuple[re.Match, re.Match] | str | None:
    """The begin and end lines (outside fenced code), a problem with them, or None when there are none."""
    begins, ends = _unfenced(_BEGIN, text), _unfenced(_END, text)
    if not begins and not ends:
        return None
    fix = "fix the marker lines by hand, then run `km gen-index`"
    if open_ := [m for m in begins + ends if not m.group(0).rstrip().endswith("-->")]:
        return f"a marker line of the generated ownership table does not close its comment on that line ({printable(open_[0].group(0)[:60])}): {fix}"
    if len(begins) == 1 and len(ends) == 1 and begins[0].end() < ends[0].start():
        return begins[0], ends[0]
    order = " (end above begin)" if len(begins) == 1 == len(ends) else ""
    return (f"the generated ownership table needs one line starting `{BEGIN}` and, below it, one line "
            f"`{END}`; found {len(begins)} and {len(ends)}{order}: {fix}")


def has_markers(text: str) -> bool:
    """Whether the text has a marker line of the generated table outside fenced code, broken or not."""
    return _markers(text) is not None


def has_heading(text: str, rx: re.Pattern) -> bool:
    """Whether a heading `rx` matches stands outside fenced code."""
    return bool(_unfenced(rx, text))


def generated_span(text: str) -> tuple[int, int] | None:
    """Where the generated table sits, from its begin line to the end of its end line, or None."""
    m = _markers(text)
    return (m[0].start(), m[1].end()) if isinstance(m, tuple) else None


def marker_problem(text: str) -> str | None:
    """What is wrong with the marker lines, or None (both in place, or neither)."""
    m = _markers(text)
    return m if isinstance(m, str) else None


def _gitlinks(root: Path) -> frozenset[str] | None:
    """The paths the git index holds as gitlinks (mounts), NFC-normalised; None outside a git work tree."""
    res = git("ls-files", "-z", "-s", cwd=root)
    if res.returncode:
        return None
    return frozenset(unicodedata.normalize("NFC", path) for meta, _, path in
                     (rec.partition("\t") for rec in res.stdout.split("\0")) if meta.startswith("160000"))


def _clean(value: str) -> str:
    """A value git printed, its undecodable bytes (kept as surrogates) as U+FFFD, so it can be written."""
    return value.encode("utf-8", "surrogateescape").decode("utf-8", "replace")


def rows(root: Path) -> list[tuple[str, str, str, str | None, str | None]] | None:
    """(path, name, url, branch, km-owns) of each submodule in .gitmodules whose path is a gitlink in the
    index, one per path, sorted by path; None outside a git work tree or where .gitmodules is a symbolic link."""
    links = _gitlinks(root)
    if links is None or (root / ".gitmodules").is_symlink():
        return None
    url, branch, owns = (submodule_config(root, k) for k in ("url", "branch", "km-owns"))
    out: dict[str, tuple] = {}
    for name, path in sorted(submodule_config(root, "path").items()):
        path = path.strip("/")
        if unicodedata.normalize("NFC", path) in links and path not in out:
            out[path] = tuple(v if v is None else _clean(v)
                              for v in (path, name, url.get(name, ""), branch.get(name), owns.get(name)))
    return sorted(out.values())


CELL_MAX = 200


def _cell(value: str, code: bool = False) -> str:
    """`value` as one table cell, in a code span with `code`: format characters (zero-width, bidi) dropped,
    link brackets made spaces outside a code span, whitespace collapsed, control characters and
    backticks `?`, at most CELL_MAX characters."""
    v = "".join(c for c in value if unicodedata.category(c) != "Cf")
    v = printable(" ".join((v if code else v.replace("[", " ").replace("]", " ")).split()))
    if len(v) > CELL_MAX:
        v = v[:CELL_MAX - 1].rstrip() + "\u2026"
    v = v.replace("|", "\\|")
    return f"`{v}`" if code else v.replace("<", "&lt;")


def _url(url: str) -> str:
    """A url without user info (a token or password), query, fragment and trailing .git; scp-style
    `user@host:path` loses its user too. A local path is kept as it is, but for .git."""
    url = url.strip()
    if mo := re.match(r"([A-Za-z][A-Za-z0-9+.-]*://)(?:[^/?#]*@)?([^?#]*)", url):
        url = mo.group(1) + mo.group(2)
    elif mo := re.match(r"[^/@:]+@([^/:]+:[^?#]*)", url):
        url = mo.group(1)
    return url[:-4] if url.endswith(".git") else url


def table(found: list) -> str:
    """The generated block's content for rows() `found`."""
    if not found:
        return NONE
    lines = [HEADER]
    for path, _name, url, branch, owns in found:
        where = "default" if branch is None else "this brain's branch" if branch.strip() == "." else _cell(branch, code=True)
        lines.append(f"| {_cell(path, code=True)} | {_cell(_url(url), code=True)} | {where} | {_cell(owns) if owns and owns.strip() else '_not stated_'} |")
    return "\n".join(lines)


def render(text: str, root: Path) -> str | None:
    """`text` with the generated table brought up to date, everything outside the markers kept byte
    for byte; None where km leaves the file alone: no markers, broken ones (marker_problem), or no git
    index to read the mounts from."""
    m = _markers(text)
    found = rows(root) if isinstance(m, tuple) else None
    return None if found is None else _fill(text, m, found)


def _fill(text: str, markers: tuple[re.Match, re.Match], found: list) -> str:
    begin, end = markers
    return text[:begin.end()] + "\n\n" + table(found) + "\n\n" + text[end.start():]


def _hand_rows(text: str) -> list[tuple[str, str]]:
    """(topic, home) of each body row of a table headed Topic in the `## Ownership` section, outside the
    generated block, HTML comments and fenced code."""
    for a, b in reversed(_fenced(text)):          # fenced code, offsets kept: a blank line per line
        text = text[:a] + "\n" * text.count("\n", a, b) + text[b:]
    sec = _SECTION.search(text)
    if not sec:
        return []
    nxt = _H2.search(text, sec.end())
    body = text[sec.end():nxt.start() if nxt else len(text)]
    body = re.sub(r"(?ms)^<!-- km:ownership:begin\b.*?^<!-- km:ownership:end\b[^\n]*", "", body)
    body = re.sub(r"(?s)<!--.*?-->", "", body)
    out: list[tuple[str, str]] = []
    block: list[list[str]] = []
    for line in [*body.splitlines(), ""]:
        if line.lstrip().startswith("|"):
            block.append([c.strip() for c in re.split(r"(?<!\\)\|", line.strip().strip("|"))])
            continue
        if len(block) > 2 and block[0][0].casefold() == "topic" and all(re.fullmatch(r":?-+:?", c) for c in block[1]):
            out += [(r[0], r[1] if len(r) > 1 else "") for r in block[2:] if any(r)]
        block = []
    return out


_HOME = re.compile(r"\]\(|\]\[|\[\[|<[A-Za-z][A-Za-z0-9+.-]*:|\b[A-Za-z][A-Za-z0-9+.-]*://", re.I)


def problems(text: str, root: Path) -> list[tuple[str, str]]:
    """The ownership warnings for CONVENTIONS.md `text`, as (category, detail)."""
    out: list[tuple[str, str]] = []
    m = _markers(text)
    if isinstance(m, str):
        out.append(("ownership-markers", m))
    elif m and (found := rows(root)) is not None:
        if _fill(text, m, found) != text:
            out.append(("ownership-stale", "the mounted-repositories table differs from .gitmodules: run `km gen-index` "
                                           "and commit CONVENTIONS.md"))
        for path, name, _url_, _branch, owns in found:
            if not (owns and owns.strip()):
                fix = command('git config -f .gitmodules {key} "<topics>"', key=f"submodule.{name}.km-owns")
                out.append(("ownership-topic", f"the mount {printable(path)} does not say what it holds: set "
                                               f"{fix or 'its km-owns key in .gitmodules'}, then `km gen-index`"))
    seen: set[str] = set()
    for topic, home in _hand_rows(text):
        if not _HOME.search(home):
            out.append(("ownership-home", f"the row {printable(topic)!r} names no home: link the doc, folder or mount "
                                          f"that holds it, or give the URL of its source"))
        key = " ".join(topic.casefold().split())
        if key in seen:
            out.append(("ownership-duplicate", f"the topic {printable(topic)!r} has more than one row: keep one home per topic"))
        seen.add(key)
    return out
